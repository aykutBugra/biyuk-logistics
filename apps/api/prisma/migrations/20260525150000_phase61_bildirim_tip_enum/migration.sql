-- Phase 6.1 Faz 4: Bildirim.tip as PostgreSQL enum

CREATE TYPE "BildirimTipi" AS ENUM (
  'TEKLIF_GELDI',
  'TEKLIF_KABUL_EDILDI',
  'TEKLIF_REDDEDILDI',
  'MESAJ_GELDI',
  'KARSI_TEKLIF_GELDI',
  'IS_BASLADI',
  'IS_TAMAMLANDI',
  'TESLIM_ONAYI_BEKLIYOR',
  'RATING_ALDIN',
  'RATING_BEKLIYOR'
);

ALTER TABLE "Bildirim"
  ADD COLUMN "tipEnum" "BildirimTipi";

UPDATE "Bildirim"
SET "tipEnum" = CASE UPPER(TRIM("tip"))
  WHEN 'TEKLIF_GELDI' THEN 'TEKLIF_GELDI'::"BildirimTipi"
  WHEN 'TEKLIF_KABUL_EDILDI' THEN 'TEKLIF_KABUL_EDILDI'::"BildirimTipi"
  WHEN 'TEKLIF_REDDEDILDI' THEN 'TEKLIF_REDDEDILDI'::"BildirimTipi"
  WHEN 'MESAJ_GELDI' THEN 'MESAJ_GELDI'::"BildirimTipi"
  WHEN 'KARSI_TEKLIF_GELDI' THEN 'KARSI_TEKLIF_GELDI'::"BildirimTipi"
  WHEN 'IS_BASLADI' THEN 'IS_BASLADI'::"BildirimTipi"
  WHEN 'IS_TAMAMLANDI' THEN 'IS_TAMAMLANDI'::"BildirimTipi"
  WHEN 'TESLIM_ONAYI_BEKLIYOR' THEN 'TESLIM_ONAYI_BEKLIYOR'::"BildirimTipi"
  WHEN 'RATING_ALDIN' THEN 'RATING_ALDIN'::"BildirimTipi"
  WHEN 'RATING_BEKLIYOR' THEN 'RATING_BEKLIYOR'::"BildirimTipi"
  ELSE 'MESAJ_GELDI'::"BildirimTipi"
END;

ALTER TABLE "Bildirim"
  ALTER COLUMN "tipEnum" SET NOT NULL;

ALTER TABLE "Bildirim" DROP COLUMN "tip";

ALTER TABLE "Bildirim" RENAME COLUMN "tipEnum" TO "tip";
